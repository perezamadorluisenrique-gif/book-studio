export type Lang = keyof typeof STRINGS;

export const fill = (s: string, vars: Record<string, string | number>): string => s.replace(/\{(\w+)\}/g, (_, k: string) => String(vars[k] ?? `{${k}}`));

export const routePath = (lang: Lang, tool: keyof typeof routes.tools): string => `${lang}/${routes.hub[lang]}/${routes.tools[tool][lang]}/`;
export const hubPath = (lang: Lang): string => `${lang}/${routes.hub[lang]}/`;
