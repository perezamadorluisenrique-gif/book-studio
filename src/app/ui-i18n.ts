// Translations for the screen text of Book Studio (buttons, labels, messages), in English and Spanish.
// t("key") gives the text in the current language; the web app picks it and the Obsidian plugin always stays in English.
// Text that comes from the book engine (problems, accessibility findings, preflight checks) is not translated here.

export type Locale = "en" | "es";

let current: Locale = "en";

/** Choose the language of everything built from now on. */
export function setLocale(locale: Locale): void {
  current = locale;
}

export function getLocale(): Locale {
  return current;
}

/** "es", "es-MX"… give Spanish; anything else gives English. */
export function detectLocale(language: string | undefined | null): Locale {
  return /^es(\b|-|_)/i.test(language ?? "") ? "es" : "en";
}

