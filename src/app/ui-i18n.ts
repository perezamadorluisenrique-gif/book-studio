type Params = Record<string, string | number>;

/** The text for `key` in the current language, with {x} replaced by params.x. */
export function t(key: Key, params?: Params): string {
  const text = (current === "es" ? ES : EN)[key];
  if (!params) return text;
  return text.replace(/\{(\w+)\}/g, (m, name: string) => (name in params ? String(params[name]) : m));
}

/** Like t() for a count: uses key.one when n is 1 and key.other otherwise; {n} is the count. */
export function tn(key: string, n: number, params?: Params): string {
  return t(`${key}.${n === 1 ? "one" : "other"}` as Key, { ...params, n });
}
